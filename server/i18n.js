export const SERVER_LANGUAGES = Object.keys(TABLES);

/** The language to write to someone in: the one they chose, else the one their browser last showed. */
export const languageOf = (user) => {
  const code = user?.settings?.language || user?.settings?.uiLanguage || 'en';
  return Object.hasOwn(TABLES, code) ? code : 'en';
};

/** `text` in `lang`, with {name} places filled from `values`. */
export function say(lang, text, values = {}) {
  const template = Object.hasOwn(TABLES, lang) && Object.hasOwn(TABLES[lang], text) ? TABLES[lang][text] : text;
  return template.replace(/\{(\w+)\}/g, (whole, name) => (Object.hasOwn(values, name) ? String(values[name]) : whole));
}

/** An episode label as stored with a show ("Episode 5"; "S2E3" is the same everywhere). */
export function sayLabel(lang, label) {
  const hit = /^Episode (\d+)$/.exec(String(label));
  return hit ? say(lang, 'Episode {n}', { n: hit[1] }) : String(label);
}
